import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';

const files=['core.js','dating-model.js','trust.js','date-lifecycle.js','local-repository.js','app-state.js'];
const source=(await Promise.all(files.map(file=>readFile(new URL('./dist/'+file,import.meta.url),'utf8')))).join('\n');
const context=vm.createContext({assert,structuredClone,console});
vm.runInContext(source+`
  const photo='data:image/jpeg;base64,'+'A'.repeat(120000);
  const photo2='data:image/jpeg;base64,'+'B'.repeat(120000);
  const photo3='data:image/jpeg;base64,'+'C'.repeat(120000);
  const data=new Map(),writes=[],deletes=[];let failCore=false;
  const driver={getItem:key=>data.get(key)??null,setItem(key,value){if(failCore&&key==='demo')throw new Error('quota');writes.push({key,bytes:value.length});data.set(key,value);},removeItem(key){deletes.push(key);data.delete(key);}};
  const repo=LocalRepository.create(driver,'demo');
  let saved=AppState.create();saved.profile.photos=[photo,photo2];saved.drafts.profile={step:0,draft:{...saved.profile,photos:[photo]}};
  repo.write(saved);
  assert.equal(writes.filter(w=>w.key!=='demo').length,2,'A shared photo in profile/draft is stored once');
  assert.ok(writes.find(w=>w.key==='demo').bytes<5000,'The state document contains photo references rather than image bytes');
  const initialWrites=writes.length;
  repo.write(saved);assert.equal(writes.length,initialWrites,'An unchanged state causes no storage writes');
  for(let i=0;i<20;i++){saved.profile.name='Draft '+i;repo.write(saved);}
  assert.equal(writes.filter(w=>w.key!=='demo').length,2,'Twenty edits never rewrite image assets');
  assert.ok(writes.filter(w=>w.key==='demo').every(w=>w.bytes<5000));
  assert.deepEqual(LocalRepository.create(driver,'demo').read().profile.photos,[photo,photo2]);
  const oldDocument=data.get('demo'),oldAssets=[...data.keys()].filter(k=>k!=='demo');
  failCore=true;
  assert.throws(()=>repo.write({...saved,profile:{...saved.profile,photos:[photo3]}}),/quota/);
  failCore=false;
  assert.equal(data.get('demo'),oldDocument,'A failed state commit leaves the previous document intact');
  assert.ok(oldAssets.every(key=>data.has(key)),'A failed commit does not delete previously committed photos');
  assert.equal([...data.keys()].filter(k=>k!=='demo').length,2,'New assets are rolled back after a failed commit');
  saved.profile.photos=[photo2];saved.drafts.profile=null;repo.write(saved);
  assert.equal([...data.keys()].filter(k=>k!=='demo').length,1,'Removed photos are reclaimed after the state commits');
  data.set('unrelated','keep me');repo.write(AppState.create());
  assert.equal([...data.keys()].filter(k=>k.startsWith('demo:photo:')).length,0,'Reset removes referenced image assets');
  assert.equal(data.get('unrelated'),'keep me','Reset never removes another app’s data');
  data.set('legacy',JSON.stringify({...saved,profile:{...saved.profile,photos:[photo]}}));
  const legacy=LocalRepository.create(driver,'legacy');const loadedLegacy=legacy.read();legacy.write(loadedLegacy);
  assert.equal(legacy.read().profile.photos[0],photo,'Inline legacy photos migrate without losing the photo');
  assert.ok(data.get('legacy').length<5000);

  const now=Date.parse('2026-10-20T18:00:00Z');
  const booking={id:'date-a',matchId:'021',venueId:'juniper',timestamp:Dating.timestamp('2026-10-22','18:00'),proposalRevision:1,marker:{colour:'navy',top:'jacket'}};
  let state={...AppState.create(),booking};
  assert.equal(DateLifecycle.updateFeedback(state,'showed','yes',now).ok,false,'Future-date feedback cannot be submitted through a stale action');
  state.dateClock='after';
  assert.equal(DateLifecycle.finish(state,now).ok,false,'An arbitrary finish action cannot create a mutual result');
  const f={...DateLifecycle.emptyFeedback(booking),showed:'yes',stars:5,again:'no',contact:'@private',submitted:true,their:'yes'};
  assert.equal(DateLifecycle.canReveal({...state,feedback:f},now),false,'One-sided or corrupted restored feedback never reveals photos/contact');
  assert.equal(DateLifecycle.normalizeFeedback(f,booking).submitted,false);
  assert.equal(DateLifecycle.normalizeFeedback({...f,bookingId:'old-date'},booking),null,'Feedback is scoped to its date');
  for(const [field,value] of [['showed','yes'],['stars',5],['again','yes'],['contact','@example.sample']])state=DateLifecycle.updateFeedback(state,field,value,now).state;
  const beforeSubmit=structuredClone(state);state=DateLifecycle.submitFeedback(state,now).state;
  assert.equal(beforeSubmit.feedback.submitted,false,'Commands do not mutate the previous state');
  assert.equal(DateLifecycle.canReveal(state,now),false,'Submitting your own yes is insufficient');
  assert.equal(DateLifecycle.partnerDecision(state,'old-date','yes',now).ok,false,'A reply for another date is ignored');
  state=DateLifecycle.partnerDecision(state,'date-a','yes',now).state;
  assert.equal(DateLifecycle.canReveal(state,now),true);
  assert.equal(DateLifecycle.partnerDecision(state,'date-a','no',now).ok,false,'A stale reply cannot replace an already recorded decision');
  const finished=DateLifecycle.finish(state,now).state;
  assert.equal(finished.pastDates[0].outcome,'revealed');assert.equal(finished.feedback,null);assert.equal(finished.booking,null);
  assert.equal(DateLifecycle.finish(finished,now).ok,false,'Finishing twice cannot double-count a date');
  let noShow={...AppState.create(),booking,dateClock:'after'};
  noShow=DateLifecycle.updateFeedback(noShow,'showed','no',now).state;
  noShow=DateLifecycle.submitFeedback(noShow,now).state;
  assert.equal(noShow.record.noShows,0,'Being stood up never counts as your no-show');
  assert.equal(Trust.record('021',noShow.reliabilityOverrides).noShows,1,'A local sample no-show affects that counterpart’s demo record');
  assert.equal(Trust.record('021').noShows,0,'Sample fixture records are immutable to consumers');
  assert.ok(Trust.reliabilityPenalty('021',noShow.reliabilityOverrides)>Trust.reliabilityPenalty('021'));
  assert.equal(AppState.hydrate(noShow).reliabilityOverrides['021'].noShows,1,'Demo record changes survive reload');
  let changedMind={...AppState.create(),booking,dateClock:'after',feedback:{...DateLifecycle.emptyFeedback(booking),showed:'yes',stars:5,again:'yes',contact:'@private'}};
  changedMind=DateLifecycle.updateFeedback(changedMind,'again','no',now).state;
  assert.equal(changedMind.feedback.contact,'','Choosing no removes the previously typed sharing contact');
  assert.equal(DateLifecycle.submitFeedback(changedMind,now).state.feedback,null,'Passing discards private sharing details');
  const lateNow=booking.timestamp-23*3600000;
  const cancelled=DateLifecycle.cancel({...AppState.create(),booking},'Plans changed',lateNow);
  assert.equal(cancelled.fee,20);assert.equal(cancelled.state.record.lateCancels,1);
  assert.equal(DateLifecycle.cancel(cancelled.state,'Plans changed',lateNow).ok,false,'A repeated cancellation does not add a second penalty');
  assert.equal(DateLifecycle.cancel({...AppState.create(),booking},'Safety concern',lateNow).state.record.lateCancels,0);
  assert.equal(DateLifecycle.cancel({...AppState.create(),booking},'Plans changed',booking.timestamp+1).ok,false,'During-date safety tools are separate from late cancellation');
  const morning={...booking,timestamp:Dating.timestamp('2026-10-22','09:00')};
  assert.equal(DateLifecycle.recognitionVisible({...AppState.create(),booking:morning},Date.parse('2026-10-22T03:00:00Z')),false,'Within 24 hours is not the same as the date’s local calendar day');
  assert.equal(DateLifecycle.recognitionVisible({...AppState.create(),booking:morning},Date.parse('2026-10-22T07:00:00Z')),true);
  const self={...Dating.defaultProfile(),complete:true,age:27,gender:'Man',intent:'A long-term relationship',energy:'Somewhere in between',activity:'Active',pets:'Love animals',selfSmoking:'Non-smoker',ownPolitics:'Progressive / left',billPreferences:['own']};
  const peer=Dating.person('021',now),open=Dating.defaultPreferences();
  assert.equal(Dating.eligible(self,open,peer),true);
  for(const [field,value] of [['energy','Introvert'],['activity','Easygoing'],['pets','Prefer pet-free'],['meet','Woman'],['intent','Open to exploring']]) {
    assert.equal(Dating.eligible(self,open,{...peer,seeking:{...peer.seeking,[field]:value}}),false,'Every counterpart requirement is checked: '+field);
  }
  assert.equal(Dating.eligible({...self,selfSmoking:'Smoker'},open,{...peer,seeking:{...peer.seeking,smoking:'Non-smoker only'}}),false,'Smoking is checked in both directions');
  assert.equal(Dating.eligible(self,open,{...peer,ownPolitics:'Centrist',seeking:{...peer.seeking,politics:'Similar views'}}),false,'Political requirements are checked in both directions');
  const one={id:'intro-one',person:{id:'021'}},two={id:'intro-two',person:{id:'021'}};
  assert.notEqual(DateLifecycle.introductionKey(one),DateLifecycle.introductionKey(two),'A record unlock is per introduction, not lifetime per person');
  assert.ok(Trust.leak('six oh four'),'Spoken phone prefixes include oh');
  assert.equal(Trust.publicNote('Meet me @somewhere'),'','Restored pre-meeting notes use the allowlist');
  const hydrated=AppState.hydrate({...AppState.create(),profile:null,booking,record:{dates:Infinity,noShows:-10,lateCancels:2.5},pastDates:[{...booking,stars:999999999,outcome:'revealed'}]});
  assert.equal(hydrated.booking.id,booking.id,'A malformed optional profile subtree does not erase the saved date');
  assert.equal(hydrated.record.dates,0);assert.equal(hydrated.record.noShows,0);assert.equal(hydrated.record.lateCancels,2);assert.equal(hydrated.pastDates[0].stars,null);
`,context);
console.log('Passed persistence size/deduplication/rollback/migration, date-scoped feedback, mutual reveal, stale replies, cancellation, reliability and calendar-day privacy regressions.');
